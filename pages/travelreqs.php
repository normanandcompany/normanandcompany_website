    <h1>Travel Requirements</h1>

<p>Traveling to the Caribbean may involve different documentation requirements depending on your citizenship, how you are traveling, where your trip begins and ends, and which destinations you will visit. A traveler flying to a Caribbean resort will generally face different requirements than a traveler taking a round-trip cruise from a United States port.</p>

<p>Before leaving home, every traveler should verify the requirements of the airline, cruise line, resort destination, connecting countries, and countries listed on the itinerary. Having the correct documentation is the traveler’s responsibility, and passengers without acceptable documents may be denied boarding or entry.</p>

<h2>Do U.S. Citizens Need a Passport for Caribbean Travel?</h2>

<p>For most Caribbean vacations, a valid passport book is the safest and most widely accepted form of identification.</p>

<p>Whether a passport is legally required depends largely on whether you are flying, cruising, or traveling to a United States territory.</p>

<h3>Flying to a Caribbean Resort</h3>

<p>U.S. citizens flying to an independent Caribbean country generally need a valid U.S. passport book. A birth certificate, driver’s license, REAL ID, or passport card is not a substitute for a passport book when traveling internationally by air.</p>

<p>The U.S. passport card may be used for certain land and sea travel between the United States, Canada, Mexico, Bermuda, and some Caribbean countries, but it cannot be used for international air travel.</p>

<p>Travelers should also confirm:</p>

<ul>
    <li>How long the passport must remain valid</li>
    <li>Whether a tourist visa or electronic travel authorization is required</li>
    <li>Whether proof of return or onward travel is required</li>
    <li>Whether proof of lodging or sufficient funds must be presented</li>
    <li>Whether an online immigration or customs form must be completed</li>
</ul>

<p>Passport-validity rules are not identical throughout the Caribbean. Some destinations require only that the passport remain valid during the visit, while others may require several months of remaining validity. Travelers should check the requirements for the specific country instead of assuming one rule applies throughout the region.</p>

<h3>Traveling to Puerto Rico or the U.S. Virgin Islands</h3>

<p>Puerto Rico and the U.S. Virgin Islands are United States territories. Travel directly between the U.S. mainland and these territories is generally treated as domestic travel for U.S. citizens and is not subject to the same passport requirements as travel to a foreign Caribbean country.</p>

<p>However, travelers should still carry acceptable government-issued identification. A passport may also become necessary if the itinerary includes a foreign island, an international flight connection, or a cruise that visits another country.</p>

<h2>Passport Requirements for Caribbean Cruises</h2>

<p>Cruise documentation requirements depend on whether the voyage is considered a closed-loop cruise.</p>

<h3>What Is a Closed-Loop Cruise?</h3>

<p>A closed-loop cruise begins and ends at the same United States port. For example, a cruise that leaves from Miami, visits several Caribbean islands, and returns to Miami may qualify as a closed-loop cruise.</p>

<p>U.S. citizens taking qualifying closed-loop cruises may be permitted to travel with proof of citizenship instead of a passport. Acceptable documents may include:</p>

<ul>
    <li>A valid U.S. passport</li>
    <li>An official government-issued birth certificate</li>
    <li>A Consular Report of Birth Abroad</li>
    <li>A Certificate of Naturalization</li>
    <li>An Enhanced Driver’s License</li>
</ul>

<p>Travelers who are age 16 or older will normally also need a government-issued photo ID, such as a driver’s license.</p>

<p>The birth certificate should be an official government-issued record from a state or local vital-records office. A hospital-issued souvenir certificate, footprint certificate, or decorative birth record should not be treated as an official citizenship document.</p>

<p>Cruise lines may establish documentation rules that are more restrictive than the minimum United States reentry requirements. In addition, a country visited during the cruise may require a passport even when the United States would allow the passenger to return using a birth certificate and photo identification.</p>

<p>Travelers must check both the cruise line’s requirements and the requirements of every destination included on the itinerary.</p>

<h3>When a Passport Is Usually Required for a Cruise</h3>

<p>A passport book will generally be required when:</p>

<ul>
    <li>The cruise begins outside the United States</li>
    <li>The cruise ends at a different port from where it began</li>
    <li>The cruise begins at one U.S. port and ends at another</li>
    <li>The traveler must fly internationally to reach the departure port</li>
    <li>The traveler will fly home from a foreign destination</li>
    <li>A country on the itinerary requires cruise passengers to carry passports</li>
    <li>The traveler is not eligible for the U.S. closed-loop cruise exception</li>
</ul>

<p>Even when a passport is not strictly required, carrying a valid passport book is strongly recommended.</p>

<h3>Why Cruise Passengers Should Carry Passport Books</h3>

<p>A birth certificate and photo ID may allow an eligible U.S. citizen to take certain closed-loop cruises, but those documents generally will not allow the traveler to fly internationally.</p>

<p>A passenger may need to fly home unexpectedly because of:</p>

<ul>
    <li>A medical emergency</li>
    <li>An injury or hospitalization</li>
    <li>A family emergency at home</li>
    <li>Missing the ship in a foreign port</li>
    <li>A mechanical problem or itinerary interruption</li>
    <li>Being removed from the ship</li>
    <li>Severe weather or another emergency</li>
</ul>

<p>The U.S. Department of State recommends passport books for cruise travelers because a passport book may be needed to fly back to the United States following an unexpected event.</p>

<h2>Requirements for International and Non-U.S. Travelers</h2>

<p>Travelers who are not U.S. citizens should normally expect to carry a valid passport, including on cruises that begin and end at the same U.S. port.</p>

<p>Visa and entry requirements are generally based on the traveler’s citizenship, not simply where the traveler lives. A person may be permitted to visit one Caribbean country without a visa while needing a visa or travel authorization for another country on the same itinerary.</p>

<p>International travelers should verify:</p>

<ul>
    <li>Passport requirements for every destination</li>
    <li>Visa or electronic travel authorization requirements</li>
    <li>Transit requirements for countries where flights connect</li>
    <li>Documentation needed to enter or reenter the United States</li>
    <li>Whether a multiple-entry visa is needed</li>
    <li>Passport-validity requirements</li>
    <li>Requirements for infants and children</li>
</ul>

<p>Non-U.S. citizens taking a cruise from a United States port must also have documentation that allows them to return to the United States after visiting foreign ports. A closed-loop cruise does not automatically eliminate U.S. visa or immigration requirements for foreign nationals.</p>

<h3>U.S. Lawful Permanent Residents</h3>

<p>A U.S. lawful permanent resident should carry a valid Permanent Resident Card, commonly called a Green Card, when returning to the United States.</p>

<p>The traveler may also need a passport from their country of citizenship, a refugee travel document, or another recognized travel document to enter the Caribbean destinations being visited. Individual countries may also require a visa based on the traveler’s nationality.</p>

<p>Travelers with temporary immigration status, pending immigration applications, refugee or asylum status, advance parole, or other special circumstances should obtain appropriate immigration guidance before leaving the United States.</p>

<h2>Travel Requirements for Children</h2>

<p>Children are generally subject to many of the same international documentation requirements as adults. A child does not automatically travel under a parent’s passport, and even infants may need their own passport.</p>

<h3>Children Flying Internationally</h3>

<p>Every U.S. citizen child, including an infant or newborn, normally needs an individual passport book when traveling internationally by air.</p>

<p>Children under age 16 receive passports that are valid for five years. Parents and guardians should apply well before the trip and should not book nonrefundable travel based solely on an expected passport-processing date.</p>

<h3>Children on Closed-Loop Cruises</h3>

<p>A U.S. citizen child may be permitted to use a government-issued birth certificate on a qualifying closed-loop cruise. However, cruise-line requirements and destination-country requirements must still be checked.</p>

<p>Parents should not assume that a birth certificate will be accepted simply because the cruise begins and ends in the United States. Certain itineraries, cruise lines, or destinations may still require a passport.</p>

<p>Obtaining a passport book for the child provides greater protection if the family must leave the cruise and fly home unexpectedly.</p>

<h3>Documents Showing the Parent-Child Relationship</h3>

<p>Parents and guardians should carry a copy of each child’s birth certificate or another document showing their legal relationship to the child.</p>

<p>This is particularly important when:</p>

<ul>
    <li>The parent and child have different last names</li>
    <li>The child is traveling with only one parent</li>
    <li>The child is traveling with grandparents or other relatives</li>
    <li>The child is traveling with a school, church, or organized group</li>
    <li>The traveler is the child’s legal guardian</li>
    <li>Custody arrangements affect the child’s ability to travel</li>
</ul>

<h3>Traveling Without Both Parents</h3>

<p>When a child travels with only one parent, with a guardian, or with another adult, the accompanying adult should carry a signed consent letter from the absent parent or parents.</p>

<p>The letter should preferably be notarized and should include:</p>

<ul>
    <li>The child’s full legal name</li>
    <li>The child’s date and place of birth</li>
    <li>The names and contact information of the parents or guardians</li>
    <li>The name of the accompanying adult</li>
    <li>The countries and destinations being visited</li>
    <li>The dates of travel</li>
    <li>Permission for the child to travel</li>
    <li>Permission to obtain emergency medical treatment, when appropriate</li>
</ul>

<p>The United States does not ordinarily require proof of both parents’ permission for a child to leave the country, but foreign governments, airlines, immigration officials, and cruise lines may require it.</p>

<p>When applicable, the accompanying adult should also carry copies of:</p>

<ul>
    <li>A sole-custody order</li>
    <li>A guardianship order</li>
    <li>An adoption decree</li>
    <li>A court order authorizing international travel</li>
    <li>The death certificate of a deceased parent</li>
    <li>Documentation explaining a legal name difference</li>
</ul>

<p>Each destination has its own rules, and some Caribbean countries closely examine documentation for minors as a child-protection measure.</p>

<h2>Names Must Match the Travel Documents</h2>

<p>The name on the airline reservation, cruise reservation, passport, birth certificate, and other identification should match as closely as possible.</p>

<p>A traveler whose current legal name differs from the name on a birth certificate or citizenship document should carry documentation explaining the change, such as:</p>

<ul>
    <li>A certified marriage certificate</li>
    <li>A divorce decree</li>
    <li>A court-ordered name-change document</li>
    <li>Another official legal record</li>
</ul>

<p>Airlines, cruise lines, security officials, and immigration authorities may request additional documentation when names do not match.</p>

<h2>Carry Physical and Electronic Copies of Travel Documents</h2>

<p>Every traveler should carry backup copies of important travel documents. Copies do not normally replace the original documents required for boarding or entry, but they can make it much easier to obtain assistance if the originals are lost, damaged, or stolen.</p>

<p>Travelers should make multiple copies of important documents, keep one set separate from the originals, and leave another set with a trusted friend or relative. Cruise travelers should also retain secure electronic images of their documents.</p>

<p>Travelers should consider copying:</p>

<ul>
    <li>The passport identification page</li>
    <li>Passport cards and government-issued identification</li>
    <li>Visas and electronic travel authorizations</li>
    <li>Birth certificates used for cruise travel</li>
    <li>Green Cards and immigration documents</li>
    <li>Cruise boarding documents</li>
    <li>Airline reservations</li>
    <li>Resort and hotel confirmations</li>
    <li>The complete travel itinerary</li>
    <li>Travel-insurance documents</li>
    <li>Emergency contact information</li>
    <li>Parental consent letters</li>
    <li>Custody or guardianship documents</li>
    <li>Prescription information and important medical records</li>
</ul>

<p>Keep the original documents in a secure carry-on bag or personal item. Do not place passports, birth certificates, Green Cards, or essential immigration documents in checked luggage.</p>

<p>A paper copy should be stored separately from the originals. Electronic copies may be kept in a password-protected cloud account, secure document application, or encrypted device. A trusted person at home should also have access to copies and the traveler’s itinerary.</p>

<p>Because travel documents contain sensitive personal information, copies should not be posted on social media or stored in an unsecured public location.</p>

<h2>Additional Documents to Consider</h2>

<p>Depending on the destination and itinerary, travelers may also need:</p>

<ul>
    <li>A visa or electronic travel authorization</li>
    <li>Proof of return or onward transportation</li>
    <li>A completed immigration or customs form</li>
    <li>Proof of resort or hotel accommodations</li>
    <li>Travel-insurance information</li>
    <li>Vaccination or health documentation</li>
    <li>Prescription medication documentation</li>
    <li>Proof of sufficient funds</li>
    <li>A driver’s license or international driving permit</li>
    <li>Cruise-line luggage tags and boarding documents</li>
    <li>Emergency medical and evacuation coverage information</li>
</ul>

<p>Requirements can change with little notice. Online immigration forms may also have submission deadlines, and some countries charge entry or departure fees.</p>

<h2>Final Documentation Checklist</h2>

<p>Before leaving for a Caribbean cruise or resort vacation, confirm that:</p>

<ul>
    <li>Every traveler has the required passport, citizenship, and identification documents</li>
    <li>Each passport remains valid for the required period</li>
    <li>Every child has their own required documents</li>
    <li>Parental consent and custody documents are available when applicable</li>
    <li>Names on reservations match the identification documents</li>
    <li>Required visas and travel authorizations have been approved</li>
    <li>Return or onward travel can be documented</li>
    <li>Original documents are packed in carry-on luggage</li>
    <li>Paper copies are stored separately from the originals</li>
    <li>Secure electronic copies are available</li>
    <li>A trusted person at home has copies of the documents and itinerary</li>
    <li>The airline, cruise line, and every destination have been checked for current requirements</li>
</ul>

<h2>Verify Requirements Before Traveling</h2>

<p>Travel documentation rules depend on citizenship, immigration status, age, transportation method, departure port, destination, and itinerary. Information that applies to one Caribbean island or cruise may not apply to another.</p>

<p>Before departure, travelers should verify the latest requirements through the appropriate government authorities, destination embassy or consulate, airline, cruise line, and travel provider. Travelers should never rely solely on a previous trip or another passenger’s experience when deciding which documents to carry.</p>

<p><strong>Important:</strong> Travel requirements may change at any time. The information provided on this page is intended for general planning purposes and should not be considered legal or immigration advice.</p>

